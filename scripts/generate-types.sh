#!/usr/bin/env bash
#
# Writes TypeScript declarations of the Rust types the window receives, from the types
# themselves (ts-rs), into webview/pages/app/core/generated/. The interface imports them, so a
# renamed or retyped field is a type error instead of a surprise at run time.
#
#   bash scripts/generate-types.sh           write them
#   bash scripts/generate-types.sh --check   fail when they are out of date (CI)
#
# A type is exported by deriving ts-rs's TS when the `typescript` feature is on:
#   #[cfg_attr(feature = "typescript", derive(ts_rs::TS), ts(export))]
set -euo pipefail

repo_root=$(cd "$(dirname "$0")/.." && pwd)
out="$repo_root/webview/pages/app/core/generated"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# ts-rs writes one file per type when its export tests run.
(cd "$repo_root/src-tauri" &&
    TS_RS_EXPORT_DIR="$tmp" cargo test --quiet --lib -p cortex -p cortex-kernel -p cortex-store --features cortex/typescript export_bindings >/dev/null)

{
    echo "// Generated by scripts/generate-types.sh from the Rust types; do not edit."
    echo
    for file in "$tmp"/*.ts; do
        # One module: drop the per-file imports of each other and the per-file banners.
        grep -v '^import type\|^// This file was generated' "$file" | sed '/^$/d'
        echo
    done
} >"$tmp/ipc.ts.new"

if [ "${1:-}" = "--check" ]; then
    if ! cmp -s "$tmp/ipc.ts.new" "$out/ipc.ts"; then
        echo "generate-types: webview/pages/app/core/generated/ipc.ts is out of date; run bash scripts/generate-types.sh" >&2
        exit 1
    fi
    echo "generate-types: ok"
    exit 0
fi
mkdir -p "$out"
mv "$tmp/ipc.ts.new" "$out/ipc.ts"
echo "generate-types: wrote webview/pages/app/core/generated/ipc.ts"
